import "./load-env";
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { drizzle } from "drizzle-orm/node-postgres";
import { migrate } from "drizzle-orm/node-postgres/migrator";
import { Client, Pool } from "pg";

/**
 * Every worktree gets its own database, so parallel agents can run the suite at
 * the same time without truncating each other's rows. The name is derived from
 * the current branch.
 *
 *   npm run db:test:setup   # create if missing + migrate + write .env.test.local
 *   npm run db:test:reset   # drop, recreate, migrate
 */

function branchSlug(): string {
  try {
    const branch = execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], {
      encoding: "utf8",
    }).trim();
    const slug = branch
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "_")
      .replace(/^_+|_+$/g, "");
    return slug || "detached";
  } catch {
    return "local";
  }
}

function quoteIdent(name: string): string {
  return `"${name.replaceAll('"', '""')}"`;
}

async function main() {
  const reset = process.argv.includes("--reset");
  const adminUrl = process.env.DATABASE_URL_UNPOOLED ?? process.env.DATABASE_URL;
  if (!adminUrl) throw new Error("DATABASE_URL is not set");

  const databaseName = `code_feast_test_${branchSlug()}`.slice(0, 60);
  if (!databaseName.includes("_test")) {
    throw new Error("Refusing to touch a database without _test in its name");
  }

  const admin = new Client({ connectionString: adminUrl });
  await admin.connect();
  try {
    const existing = await admin.query(
      "select 1 from pg_database where datname = $1",
      [databaseName],
    );
    if (existing.rowCount && reset) {
      await admin.query(
        `drop database if exists ${quoteIdent(databaseName)} with (force)`,
      );
    }
    if (!existing.rowCount || reset) {
      await admin.query(`create database ${quoteIdent(databaseName)}`);
      console.log(`Created database ${databaseName}`);
    } else {
      console.log(`Reusing database ${databaseName}`);
    }
  } finally {
    await admin.end();
  }

  const testUrl = new URL(adminUrl);
  testUrl.pathname = `/${databaseName}`;
  const testUrlString = testUrl.toString();

  const pool = new Pool({ connectionString: testUrlString, max: 1 });
  try {
    await migrate(drizzle(pool), { migrationsFolder: "./drizzle" });
  } finally {
    await pool.end();
  }

  writeFileSync(
    ".env.test.local",
    [
      "# Generated by scripts/setup-test-db.ts — safe to delete and regenerate.",
      `TEST_DATABASE_URL="${testUrlString}"`,
      "",
    ].join("\n"),
  );
  console.log("Migrations applied. TEST_DATABASE_URL written to .env.test.local");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
